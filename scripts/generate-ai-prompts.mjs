import { readFileSync, writeFileSync } from "node:fs";

// Convex's isolate cannot read files at runtime and its bundler has no Markdown loader.
// Keep Markdown as the source of truth and commit this reproducible bundle.
const root = new URL("../", import.meta.url);
const output = new URL("convex/model/sapopinguino/prompts.generated.ts", root);
const names = ["respell", "translate"];
const source = "// Generated by npm run prompts:generate. Edit convex/prompts/*.md instead.\n" +
  names.map((name) => {
    const prompt = readFileSync(new URL(`convex/prompts/${name}.md`, root), "utf8");
    return `export const ${name}Prompt = ${JSON.stringify(prompt)};\n`;
  }).join("");

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source) {
    throw new Error("AI prompt bundle is stale. Run npm run prompts:generate.");
  }
} else {
  writeFileSync(output, source);
}
